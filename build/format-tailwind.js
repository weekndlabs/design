import { ROLES, TERMINAL } from '../lib/tokens.js';

/**
 * Tailwind preset. Colours resolve through the CSS variables so a consumer
 * switching data-theme restyles without a rebuild.
 *
 * No `<alpha-value>` slot: the variables hold real oklch colours now, so there is
 * nothing to splice into an rgb() wrapper. Tailwind v4 resolves `bg-primary/30`
 * through color-mix() on the real colour instead.
 */
export const formatTailwind = ({ dictionary }) => {
  const colors = Object.fromEntries(
    ROLES.filter((r) => r !== 'radius').map((role) => [role, { DEFAULT: `var(--wl-${role})` }])
  );
  const group = (prefix) =>
    Object.fromEntries(
      dictionary.allTokens
        .filter((t) => t.path[0] === prefix)
        .map((t) => [t.path.slice(1).join('-'), `var(--wl-${t.path.join('-')})`])
    );

  // Tailwind's own spacing scale is numeric, and so is this one, but they
  // disagree from step 5 upward: 20 vs 24, 24 vs 32, 36 vs 96. Emitting the
  // system's steps under those keys silently redefines `p-6` and `h-9` for
  // every consumer, and the low steps happen to match, so it looks correct
  // until a layout explodes somewhere unrelated. Prefixed, `p-wl-5` asks for
  // the system's step and `p-5` still means what Tailwind says it means.
  const spacing = Object.fromEntries(
    Object.entries(group('space')).map(([step, value]) => [`wl-${step}`, value])
  );

  const extend = {
    colors: {
      ...colors,
      terminal: Object.fromEntries(TERMINAL.map((r) => [
        r === 'ground' ? 'DEFAULT' : r, `var(--wl-terminal-${r})`,
      ])),
    },
    spacing,
    // DEFAULT is the per-theme ladder, `full` the shared pill.
    borderRadius: { DEFAULT: 'var(--wl-radius)', ...group('radius') },
    maxWidth: group('measure'),
    fontSize: group('text'),
    letterSpacing: group('tracking'),
    fontFamily: group('font'),
    fontWeight: group('weight'),
    lineHeight: group('leading'),
  };

  return [
    '// Generated by @weekndlabs/design. Do not edit.',
    `export default ${JSON.stringify({ theme: { extend } }, null, 2)};`,
  ].join('\n');
};
