import { THEMES, ROLES, TERMINAL } from '../lib/tokens.js';

const union = (values) => values.map((v) => `'${v}'`).join(' | ');

/**
 * Types for `dist/tokens.js`, generated beside the values they describe.
 *
 * Hand-writing these would mean a second list of every role, kept in step by
 * memory. Generating them means a role added to `ROLES` is typed the moment it
 * exists, and a typo in a consumer's `themes.dark.forground` fails to compile
 * rather than resolving to undefined at runtime.
 */
export const formatDts = ({ dictionary }) => {
  const textRoles = dictionary.allTokens
    .filter((t) => t.path[0] === 'text')
    .map((t) => t.path[1])
    .sort();
  const containers = dictionary.allTokens
    .filter((t) => t.path[0] === 'container')
    .map((t) => t.path[1]);

  return [
    '// Generated by @weekndlabs/design. Do not edit.',
    '',
    `export type Theme = ${union(THEMES)};`,
    `export type Role = ${union(ROLES)};`,
    `export type TerminalRole = ${union(TERMINAL)};`,
    `export type TextRole = ${union(textRoles)};`,
    `export type Container = ${union(containers)};`,
    '',
    '/** Every theme name, in the order the CSS emits them. */',
    'export declare const THEMES: readonly Theme[];',
    '/** Every semantic role, including `radius`, which is a length. */',
    'export declare const ROLES: readonly Role[];',
    '/** The terminal group, which is not themed. */',
    'export declare const TERMINAL: readonly TerminalRole[];',
    '/** The type scale, for the gate in `@weekndlabs/design/typography-check`. */',
    'export declare const TEXT_ROLES: readonly TextRole[];',
    '',
    '/** Resolved colours, keyed theme then role. Values are oklch, except `radius`. */',
    'export declare const themes: Record<Theme, Record<Role, string>>;',
    '/** Resolved terminal colours. One set, shared by both themes. */',
    'export declare const terminal: Record<TerminalRole, string>;',
    '/**',
    ' * Container widths, as lengths.',
    ' *',
    ' * They are here and not in the CSS because `@container` cannot read a custom',
    ' * property: the query would parse and never match.',
    ' */',
    'export declare const containers: Record<Container, string>;',
    '',
  ].join('\n');
};

/**
 * Types for `dist/tailwind.js`.
 *
 * This one references tailwindcss, which is not a dependency here. That is
 * deliberate and safe: the only consumer who resolves this file is one
 * importing the Tailwind preset, and they have Tailwind. package.json marks it
 * an optional peer so the intent is declared rather than implied.
 */
export const formatTailwindDts = () =>
  [
    '// Generated by @weekndlabs/design. Do not edit.',
    "import type { Config } from 'tailwindcss';",
    '',
    'declare const preset: Partial<Config>;',
    'export default preset;',
    '',
  ].join('\n');
