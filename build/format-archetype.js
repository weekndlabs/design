/**
 * The two page archetypes, one stylesheet each.
 *
 * A marketing page and a catalog page want different things, and forcing one
 * vocabulary on both is what makes a design system feel like a straitjacket. So
 * the core stays single and these sit on top of it. Each may define tokens of
 * its own. Neither may redefine a core one, and a gate in lib/build.test.js
 * fails if an archetype token reaches the core output.
 *
 * Tokens are scoped to a class rather than :root, so one page can hold a
 * marketing hero above a catalog shelf without either bleeding into the other.
 */
const scoped = (group, tokens) => {
  const lines = tokens
    .filter((t) => t.path[0] === 'archetype' && t.path[1] === group)
    .map((t) => `  --wl-${t.path.slice(2).join('-')}: ${t.value};`);
  if (!lines.length) throw new Error(`no tokens found for archetype.${group}`);
  return lines.join('\n');
};

const HEADER = '/* Generated by @weekndlabs/design. Do not edit. */';

export const formatMarketing = ({ dictionary }) =>
  [
    HEADER,
    `/* The page that sells one thing.
   Four tokens live only here. The hero gradient is derived from the core
   accent rather than being a colour of its own, so the archetype spends no
   new hue: change --wl-ring and the hero follows. */`,
    `.wl-marketing {\n${scoped('marketing', dictionary.allTokens)}\n}`,

    `.wl-marketing .wl-hero {
  background: var(--wl-gradient-hero);
  border-radius: var(--wl-radius-section);
  corner-shape: var(--wl-corner-shape);
  color: var(--wl-hero-fg);
  padding: var(--wl-space-8) var(--wl-space-7);
  text-align: center;
  overflow: hidden;
}`,

    `/* The one place this system spends a serif. It appears on a single line per
   page and never inside an app, which is why the face loads with the
   archetype and not with the core. */
.wl-marketing .wl-hero-title {
  font-family: var(--wl-font-sans);
  font-size: var(--wl-text-hero);
  font-weight: var(--wl-weight-display);
  letter-spacing: -0.05em;
  line-height: 1;
  text-wrap: balance;
  margin: 0;
}
.wl-marketing .wl-hero-title em {
  display: block;
  font-family: var(--wl-font-accent);
  font-style: italic;
  font-weight: var(--wl-weight-body);
  letter-spacing: -0.015em;
}`,

    `/* Near black, lit from above. The inset highlights are what make a filled
   control read as a physical key rather than a rectangle.
   Fixed rather than themed, and a token rather than a literal: this button only
   ever sits on the hero gradient, which is bright in both themes, so inverting
   it with the page would put white on pale blue. */
.wl-marketing .wl-btn-glossy {
  background: var(--wl-btn-glossy-bg);
  color: var(--wl-btn-glossy-fg);
  border: 0;
  box-shadow: var(--wl-shadow-glossy);
}`,

    `.wl-marketing .wl-section {
  background: var(--wl-muted);
  border-radius: var(--wl-radius-section);
  corner-shape: var(--wl-corner-shape);
  padding: var(--wl-space-7);
}`,

    `/* Last in the sheet on purpose. A container query ties with the rules above
   on specificity, so source order is the only thing that makes it win. */
@container (max-width: 640px) {
  .wl-marketing { --wl-radius-section: var(--wl-radius-section-narrow); }
  .wl-marketing .wl-hero { padding: var(--wl-space-6) var(--wl-space-5); }
  .wl-marketing .wl-section { padding: var(--wl-space-6) var(--wl-space-5); }
}`,
    '',
  ].join('\n\n');

export const formatCatalog = ({ dictionary }) =>
  [
    HEADER,
    `/* The page that lists many things.
   No gradient, no serif, no oversized corners. What it adds is a media ratio
   and a three step elevation ladder, because a shelf of cards is the one
   layout where lift carries meaning. */`,
    `.wl-catalog {\n${scoped('catalog', dictionary.allTokens)}\n}`,

    `.wl-catalog .wl-shelf {
  display: grid;
  grid-template-columns: 1fr 1fr;
  gap: var(--wl-space-5);
}`,

    `.wl-catalog .wl-media {
  aspect-ratio: var(--wl-card-media);
  border-radius: var(--wl-radius-window);
  corner-shape: var(--wl-corner-shape);
  box-shadow: var(--wl-shadow-2);
  overflow: hidden;
  transition: box-shadow 180ms cubic-bezier(0, 0, 0.2, 1), transform 180ms cubic-bezier(0, 0, 0.2, 1);
}
@media (hover: hover) {
  .wl-catalog a:hover .wl-media { box-shadow: var(--wl-shadow-3); transform: translateY(-2px); }
}
@media (prefers-reduced-motion: reduce) {
  .wl-catalog .wl-media { transition: none; }
  .wl-catalog a:hover .wl-media { transform: none; }
}`,

    `/* Scrolls sideways rather than wrapping. A filter row that wraps to three
   lines pushes the content it filters off the screen. */
.wl-catalog .wl-filters {
  display: flex;
  align-items: center;
  gap: var(--wl-space-2);
  overflow-x: auto;
  scroll-snap-type: x proximity;
  scrollbar-width: none;
  min-width: 0;
  flex: 1 1 auto;
}
.wl-catalog .wl-filters::-webkit-scrollbar { display: none; }
.wl-catalog .wl-filters > * { flex: 0 0 auto; scroll-snap-align: start; }
.wl-catalog .wl-filterbar { display: flex; align-items: center; gap: var(--wl-space-3); }`,

    `@container (max-width: 640px) {
  .wl-catalog .wl-shelf { grid-template-columns: 1fr; gap: var(--wl-space-4); }
  /* The segmented control moves off the scrolling row, or it scrolls away with
     the chips and the reader loses the control that reorders them. */
  .wl-catalog .wl-filterbar { flex-direction: column-reverse; align-items: flex-start; gap: var(--wl-space-2); }
  .wl-catalog .wl-filters { width: 100%; }
}`,
    '',
  ].join('\n\n');
