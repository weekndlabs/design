import { ROLES, TERMINAL } from '../lib/tokens.js';

/**
 * The Tailwind v4 bridge. A consumer imports this one file and deletes its own
 * theme block.
 *
 * `@theme inline` is what turns a variable into a utility: a `--wl-card` defined
 * only in `:root` leaves `bg-card` compiling to nothing. `inline` matters
 * specifically because it keeps the `var()` reference in the output rather than
 * resolving it at parse time, which is what lets `data-theme` restyle a built
 * page with no rebuild.
 */
export const formatShadcn = () => {
  const colors = ROLES.filter((r) => r !== 'radius')
    .map((role) => `  --color-${role}: var(--wl-${role});`)
    .join('\n');
  // Without these, `bg-terminal` and `text-terminal-green` compile to nothing,
  // and the ten tokens would only be reachable through raw var().
  const terminal = TERMINAL.map((role) =>
    `  --color-terminal-${role === 'ground' ? 'ground' : role}: var(--wl-terminal-${role});`).join('\n');

  return [
    '/* Generated by @weekndlabs/design. Do not edit. */',
    "@import './tokens.css';",
    // Component source writes `dark:` utilities and never `.dark` itself, so
    // pointing the variant here is shadcn's own customisation point rather than
    // a departure from it. One switch, and copied shadcn code still works.
    "@custom-variant dark (&:is([data-theme='dark'] *));",
    // The ladder, not just `--radius`. Tailwind resolves `rounded-md` from
    // `--radius-md`, so setting `--radius` alone leaves every corner on
    // Tailwind's own defaults and the theme's radius never renders. That shipped
    // once and was only caught by compiling the bridge for real.
    //
    // The multipliers are shadcn CLI v4's own, so a component copied from shadcn
    // lands on the radius it was drawn with.
    [
      '@theme inline {',
      colors,
      '',
      terminal,
      '',
      '  --radius: var(--wl-radius);',
      '  --radius-xs: calc(var(--wl-radius) * 0.5);',
      '  --radius-sm: calc(var(--wl-radius) * 0.75);',
      '  --radius-md: calc(var(--wl-radius) * 0.875);',
      '  --radius-lg: var(--wl-radius);',
      '  --radius-xl: calc(var(--wl-radius) * 1.5);',
      '  --radius-full: var(--wl-radius-full);',
      '}',
    ].join('\n'),
    '',
  ].join('\n\n');
};
