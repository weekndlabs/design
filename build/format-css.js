import { THEMES, ROLES, TERMINAL } from '../lib/tokens.js';

/**
 * Everything that is not a colour is unthemed and goes out as-is. Naming the
 * groups instead would mean a new group silently vanishing from the CSS until
 * someone remembered to add it here.
 */
/**
 * Container widths are the exception, and they are deliberately not here.
 *
 * `@container (max-width: var(--wl-container-narrow))` does not work, the same
 * way a media query cannot read a custom property. Emitting them as CSS
 * variables would advertise a query that silently never matches, so they ship
 * as JS values only.
 */
const CORE_EXCLUDED = new Set([
  'color', // themed, emitted above
  'container', // see the note above
  'archetype', // belongs to marketing.css and catalog.css, never to the core
]);
const isScale = (token) => !CORE_EXCLUDED.has(token.path[0]);

/**
 * One block per theme. Values go out as authored, which is oklch for colours and
 * a length for radius, so nothing here has to know which is which.
 *
 * dark is emitted twice: once under :where(:root) as the default, once under
 * [data-theme]. Consumers that never set data-theme still get a usable page.
 */
export const formatCss = ({ dictionary }) => {
  const byName = Object.fromEntries(dictionary.allTokens.map((t) => [t.path.join('.'), t.value]));
  const block = (theme, selector) => {
    const lines = ROLES.map((role) => {
      const value = byName[`color.theme.${theme}.${role}`];
      if (!value) throw new Error(`token source has no color.theme.${theme}.${role}`);
      return `  --wl-${role}: ${value};`;
    });
    return `${selector} {\n${lines.join('\n')}\n}`;
  };
  const scale = dictionary.allTokens
    .filter(isScale)
    .map((t) => `  --wl-${t.path.join('-')}: ${t.value};`)
    .join('\n');

  // Colours, but not themed, so neither branch above would have emitted them.
  // A terminal is a terminal whatever the page around it does, and one ground
  // is what keeps the palette to a single set of ratios.
  const terminal = TERMINAL.map((role) => {
    const value = byName[`color.terminal.${role}`];
    if (!value) throw new Error(`token source has no color.terminal.${role}`);
    return `  --wl-terminal-${role}: ${value};`;
  }).join('\n');

  return [
    '/* Generated by @weekndlabs/design. Do not edit. */',
    // `:where()` carries no specificity, so this block only ever applies when
    // nothing else has an opinion. A consumer whose own default is light keeps
    // it, and does not have to win an import-order argument to do so.
    block('dark', ':where(:root)'),
    ...THEMES.map((t) => block(t, `[data-theme='${t}']`)),
    // The scale stays at full specificity. Nothing else in a consumer defines
    // --wl-* names, so there is no argument here to lose.
    `:root {\n${scale}\n\n${terminal}\n}`,
  ].join('\n\n');
};
