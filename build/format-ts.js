import { THEMES, ROLES, TERMINAL } from '../lib/tokens.js';

export const formatTs = ({ dictionary }) => {
  const byName = Object.fromEntries(dictionary.allTokens.map((t) => [t.path.join('.'), t.value]));
  const themes = Object.fromEntries(
    THEMES.map((theme) => [theme, Object.fromEntries(ROLES.map((r) => [r, byName[`color.theme.${theme}.${r}`]]))])
  );
  // The type roles ship as data so lib/typography.js can read them without
  // importing lib/tokens.js, which pulls in style-dictionary. That is a
  // devDependency, and the typography gate runs in a consumer's test suite.
  const textRoles = dictionary.allTokens
    .filter((t) => t.path[0] === 'text')
    .map((t) => t.path[1])
    .sort();

  const terminal = Object.fromEntries(TERMINAL.map((r) => [r, byName[`color.terminal.${r}`]]));
  // Container widths ship here and nowhere else in a runtime form. They cannot
  // be CSS variables, because @container cannot read one.
  const containers = Object.fromEntries(
    dictionary.allTokens.filter((t) => t.path[0] === 'container').map((t) => [t.path[1], t.value])
  );

  return [
    '// Generated by @weekndlabs/design. Do not edit.',
    `export const THEMES = ${JSON.stringify(THEMES)};`,
    `export const ROLES = ${JSON.stringify(ROLES)};`,
    `export const TEXT_ROLES = ${JSON.stringify(textRoles)};`,
    `export const TERMINAL = ${JSON.stringify(TERMINAL)};`,
    `export const themes = ${JSON.stringify(themes, null, 2)};`,
    `export const terminal = ${JSON.stringify(terminal, null, 2)};`,
    `export const containers = ${JSON.stringify(containers, null, 2)};`,
  ].join('\n');
};
